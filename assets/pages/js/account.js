/* account family: overview, downloads, invoices, account details.
   Opening an account page signs in the demo account (John Smith) so developers can see it; checkout keeps the real gate.
   Orders and invoices come from GCC.orders: the demo order GCC-2026-0148, the seeded past orders and anything placed through checkout.
   Downloads and invoice files are stubs generated in the browser (a plain text file and a printable HTML invoice) until real files exist. */
(function () {
  'use strict';
  var GCC = window.GCC; if (!GCC) return;
  var $ = function (q, r) { return (r || document).querySelector(q); };
  var $$ = function (q, r) { return Array.prototype.slice.call((r || document).querySelectorAll(q)); };
  var esc = GCC.ui.esc, fmtDate = GCC.ui.fmtDate;

  if (!GCC.account.signedIn()) GCC.account.signIn();
  var page = document.body.getAttribute('data-acc');

  /* who is signed in */
  function who() {
    var a = GCC.account.get() || GCC.account.demo;
    $$('[data-acc-name]').forEach(function (n) { n.textContent = a.name; });
    $$('[data-acc-email]').forEach(function (n) { n.textContent = a.email; });
  }
  who();
  document.addEventListener('click', function (e) {
    var a = e.target.closest && e.target.closest('[data-signout]'); if (!a) return;
    e.preventDefault(); GCC.account.signOut(); GCC.ui.go('index.html');
  });

  var NUM = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten'];
  function pieceName(o) {
    var first = o.lines[0] && o.lines[0].service ? o.lines[0].service.name : 'Your order', more = o.lines.length - 1;
    return more > 0 ? first + ' and ' + (NUM[more] || more) + ' more' : first;
  }
  function project(o) { return o.lines.map(function (l) { return l.brief && l.brief.title; }).filter(Boolean).join(', '); }
  var usd = function (n) { return '<span data-usd="' + n + '">' + esc(GCC.money(n)) + '</span>'; };
  var shown = function (o) { return GCC.orders.find(o.ref).totals.show; };  /* recomputed in the current currency */
  var shortDate = function (iso) { return fmtDate(iso).replace(/ \d{4}$/, ''); };

  /* stub files */
  function save(name, type, text) {
    var url = URL.createObjectURL(new Blob([text], { type: type })), a = document.createElement('a');
    a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 2000);
  }
  function downloadFile(ref) {
    var o = GCC.orders.find(ref); if (!o || !o.file) return;
    var name = o.file.replace(/\.[a-z]+$/i, '') + '.txt';
    save(name, 'text/plain', o.file + '\n' + o.ref + ', delivered ' + fmtDate(o.date) + '\n\nDemo file. In the live site this is the signed off draft from your writer.\n');
    GCC.ui.toast('Downloaded ' + esc(name));
  }
  function downloadInvoice(ref) {
    var o = GCC.orders.find(ref); if (!o) return;
    var b = o.billing || GCC.account.demo, t = o.totals, m = function (n) { return '$' + Number(n).toFixed(2); };
    var rows = o.lines.map(function (l) {
      return '<tr><td><b>' + esc(l.service ? l.service.name : l.s) + '</b><br>' + esc(l.brief && l.brief.title || '') + '<br><small>' + esc(GCC.describe(l).join(', ')) + '</small></td><td class="r">' + m(l.price.total) + '</td></tr>';
    }).join('');
    var html = '<!doctype html><html lang="en-GB"><head><meta charset="utf-8"><title>' + esc(o.invoice) + '</title><style>body{font:15px/1.5 Georgia,serif;color:#1b2033;max-width:720px;margin:48px auto;padding:0 24px}h1{font-weight:400;font-style:italic}h1 i{color:#d7263d}table{width:100%;border-collapse:collapse;margin:24px 0}td{padding:12px 0;border-top:1px solid #d3d8e1;vertical-align:top}.r{text-align:right;white-space:nowrap}small{color:#666b7b}.t td{font-weight:bold}p{margin:4px 0}</style></head><body>' +
      '<h1>Gulf Content <i>Co.</i></h1><p><b>Invoice ' + esc(o.invoice) + '</b></p><p>Order ' + esc(o.ref) + '</p><p>Issued ' + esc(fmtDate(o.date)) + '</p>' +
      '<p style="margin-top:16px">Billed to ' + esc(b.name) + ', ' + esc(b.email) + '<br>' + esc([b.address, b.city, b.country, b.pobox ? 'PO Box ' + b.pobox : ''].filter(Boolean).join(', ')) + (b.phone ? '<br>' + esc(b.phone) : '') + '</p>' +
      '<table>' + rows + '<tr><td>Subtotal</td><td class="r">' + m(t.subtotal) + '</td></tr>' +
      (t.discount && t.discount.amount ? '<tr><td>Discount, ' + esc(t.discount.label) + '</td><td class="r">' + esc(t.discount.code) + ' minus ' + m(t.discount.amount) + '</td></tr>' : '<tr><td>Discount</td><td class="r">None</td></tr>') +
      '<tr class="t"><td>Total paid (USD)</td><td class="r">' + m(t.total) + '</td></tr></table><p><small>Demo invoice generated by the prototype.</small></p></body></html>';
    save(o.invoice + '.html', 'text/html', html);
    GCC.ui.toast('Downloaded ' + esc(o.invoice));
  }
  document.addEventListener('click', function (e) {
    var f = e.target.closest && e.target.closest('[data-file]'), i = e.target.closest && e.target.closest('[data-invoice]');
    if (f) { e.preventDefault(); downloadFile(f.getAttribute('data-file')); }
    if (i) { e.preventDefault(); downloadInvoice(i.getAttribute('data-invoice')); }
  });

  var list = GCC.orders.list();
  var delivered = list.filter(function (o) { return o.file; });

  /* overview: live order tracker and three cards */
  var STAGES = ['Brief received', 'Writing', 'Editing', 'Draft ready'];
  var STEP = { 'paid': 1, 'brief received': 1, 'writing': 1, 'editing': 2, 'delivered': 4 };
  var TICK = '<svg viewBox="0 0 16 16" aria-hidden="true"><path d="M2 8l4 4 8-9" fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  function overview() {
    var live = list.filter(function (o) { return o.status !== 'delivered'; })[0] || list[0];
    var wrap = $('#accLive');
    if (wrap && live) {
      $('#accLiveRef').textContent = live.ref + '  ·  ordered ' + fmtDate(live.date);
      $('#accLiveT').textContent = pieceName(live);
      var at = STEP[live.status] != null ? STEP[live.status] : 1;
      $('#accTrack').innerHTML = STAGES.map(function (s, i) {
        var cls = i < at ? 'done' : i === at ? 'now' : '';
        var note = i === 0 ? shortDate(live.date) : i === 3 ? 'lands in Downloads' : '';
        var pen = i === at && i === 1 ? '<span class="acc-snote pen">with your writer</span>' : '';
        return '<li class="acc-stage ' + cls + '"' + (i === at ? ' aria-current="step"' : '') + '><span class="acc-node-row"><span class="acc-node">' + (i < at ? TICK : '') + '</span>' + (i < 3 ? '<span class="acc-line"></span>' : '<span class="acc-line"></span>') +
          '</span><span class="acc-scopy"><span class="acc-sname">' + s + '</span>' + (pen || '<span class="acc-snote">' + note + '</span>') + '</span></li>';
      }).join('');
    } else if (wrap) wrap.hidden = true;
    var inv = list[0], a = GCC.account.get() || GCC.account.demo;
    var files = delivered.slice(0, 2).map(function (o) { return '<div class="acc-row"><span>' + esc(o.file) + '</span></div>'; }).join('') || '<p class="acc-none">Nothing finished yet.</p>';
    $('#accCards').innerHTML =
      '<article class="acc-card rv"><h2>Latest files</h2><div class="rule-red"></div>' + files + '<a class="tlink red" href="account-downloads.html">All downloads</a></article>' +
      (inv ? '<article class="acc-card rv"><h2>Latest invoice</h2><div class="rule-red"></div><div class="acc-row"><span>' + esc(inv.invoice) + '</span><span data-inv-total="' + esc(inv.ref) + '">' + esc(shown(inv).total) + '</span></div>' + '<div class="acc-row"><span>Discount</span><span data-inv-disc="' + esc(inv.ref) + '">' + esc(shown(inv).discountText) + '</span></div>' + '<div class="acc-row"><span>Issued</span><span>' + esc(fmtDate(inv.date)) + '</span></div><button type="button" class="tlink red" data-invoice="' + esc(inv.ref) + '">Download invoice</button></article>' : '') +
      '<article class="acc-card rv"><h2>Account details</h2><div class="rule-red"></div><div class="acc-row"><span>' + esc(a.name) + '</span></div><div class="acc-row"><span>' + esc([a.city, a.country].filter(Boolean).join(', ')) + '</span></div><a class="tlink red" href="account-details.html">Edit details</a></article>';
    GCC.ui.enhance($('#accCards'));
  }

  /* downloads: delivered orders, or the empty state (?state=empty shows it on demand) */
  function downloads() {
    var root = $('#accDl'), empty = GCC.ui.params().get('state') === 'empty' || !delivered.length;
    if (empty) {
      root.innerHTML = '<div class="acc-empty rv-kids"><p class="pen">nothing finished yet</p><p>Your first file lands here when the draft is signed off.</p><a class="btn btn-navy" href="services.html">Order a piece</a></div>';
    } else {
      root.innerHTML = '<div class="acc-dlwrap"><p class="acc-lead rv">Finished files from paid orders. Each one stays here for as long as you keep the account.</p></div>' +
        '<div class="acc-table" role="table" aria-label="Downloads"><div class="acc-thead" role="row"><span class="acc-c1" role="columnheader">Order</span><span class="acc-c2" role="columnheader">Piece</span><span class="acc-c3" role="columnheader">Project</span><span class="acc-c4" role="columnheader">Delivered</span><span class="acc-c5" role="columnheader">File</span></div>' +
        delivered.map(function (o) {
          return '<div class="acc-tr rv" role="row"><span class="acc-c1" role="cell">' + esc(o.ref) + '</span><span class="acc-c2 acc-piece" role="cell">' + esc(pieceName(o)) + '</span><span class="acc-c3" role="cell">' + esc(project(o)) + '</span><span class="acc-c4" role="cell">' + esc(fmtDate(o.date)) + '</span><span class="acc-c5" role="cell"><button type="button" class="btn btn-grey acc-btn" data-file="' + esc(o.ref) + '" aria-label="Download ' + esc(o.file) + '">Download file</button></span></div>';
        }).join('') + '</div>';
      root.style.display = 'contents';
    }
    GCC.ui.enhance(root);
  }

  /* invoices: every order */
  function invoices() {
    var root = $('#accInv');
    root.setAttribute('role', 'table'); root.setAttribute('aria-label', 'Invoices');
    /* desktop: three cells; mobile: a money stack, label left and value right (Figma 12352:6287) */
    var money3 = function (o) {
      var s = o.totals.show;
      return '<span class="acc-money">' +
        '<span class="acc-m acc-sub" role="cell"><span class="acc-ml">Subtotal</span><span>' + esc(s.subtotal) + '</span></span>' +
        '<span class="acc-m acc-disc" role="cell"><span class="acc-ml">Discount</span><span>' + esc(s.discountText) + '</span></span>' +
        '<span class="acc-m acc-tot" role="cell"><span class="acc-ml">Total</span><span>' + esc(s.total) + '</span></span></span>';
    };
    var paint = function (again) {
      var orders = GCC.orders.list();
      root.innerHTML = '<div class="acc-thead" role="row"><span class="acc-c1" role="columnheader">Invoice</span><span class="acc-c2" role="columnheader">Piece</span><span class="acc-c3" role="columnheader">Issued</span><span class="acc-m acc-sub" role="columnheader">Subtotal</span><span class="acc-m acc-disc" role="columnheader">Discount</span><span class="acc-m acc-tot" role="columnheader">Total</span><span class="acc-c5" role="columnheader">Invoice</span></div>' +
        orders.map(function (o) {
          return '<div class="acc-tr rv' + (again ? ' in' : '') + '" role="row"><span class="acc-c1" role="cell">' + esc(o.invoice) + '</span><span class="acc-c2 acc-piece" role="cell">' + esc(pieceName(o)) + '</span><span class="acc-c3" role="cell">' + esc(fmtDate(o.date)) + '</span>' + money3(o) + '<span class="acc-c5" role="cell"><button type="button" class="btn btn-grey acc-btn" data-invoice="' + esc(o.ref) + '" aria-label="Download invoice ' + esc(o.invoice) + '">Download invoice</button></span></div>';
        }).join('');
      GCC.ui.enhance(root);
    };
    paint(false);
    GCC.on('currency', function () { paint(true); });
  }

  /* account details: fill from the session, save through GCC.account.save */
  function details() {
    var f = $('#detailsForm'), a = GCC.account.get() || GCC.account.demo;
    ['name', 'email', 'phone', 'dob', 'address', 'city', 'pobox'].forEach(function (k) { var i = f.elements[k]; if (i) i.value = a[k] || ''; });
    if (a.country) f.elements.country.value = a.country;
    f.addEventListener('submit', function (e) {
      e.preventDefault();
      if (!GCC.ui.validate(f)) return;
      var d = {}; ['name', 'email', 'phone', 'dob', 'address', 'city', 'country', 'pobox'].forEach(function (k) { d[k] = f.elements[k].value.trim(); });
      var p = d.name.split(/\s+/); d.first = p[0]; d.last = p.slice(1).join(' ');
      GCC.account.save(d); who();
      GCC.ui.toast('Details saved');
    });
    var pw = $('#pwForm');
    pw.addEventListener('submit', function (e) {
      e.preventDefault();
      if (!GCC.ui.validate(pw)) return;
      GCC.ui.toast('Password updated');
    });
  }

  if (page === 'overview') {
    overview();
    GCC.on('currency', function () {
      $$('[data-inv-total]').forEach(function (n) { n.textContent = shown({ ref: n.getAttribute('data-inv-total') }).total; });
      $$('[data-inv-disc]').forEach(function (n) { n.textContent = shown({ ref: n.getAttribute('data-inv-disc') }).discountText; });
    });
  }
  if (page === 'downloads') downloads();
  if (page === 'invoices') invoices();
  if (page === 'details') details();
})();
